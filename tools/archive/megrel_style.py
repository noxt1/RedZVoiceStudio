"""Megrel Style Engine — перевод грузинского в мегрельский.

Мегрельский (მეგრელური) — западный диалект грузинского (Картвелия).
Это НЕ отдельный язык в моделях перевода: прямой модели ru->mg нет, как и
озвучки клоном голоса (XTTS v2 не поддерживает грузинский).

Конвейер:
    RU -> EN (opus-mt-ru-en) -> KA (opus-mt-en-mul, токен >>kat<<)
        -> Megrel Style Engine -> озвучка (Piper ka_GE)

Что делает стилизатор:
  * лексика: грузинские слова -> типичные мегрельские (баба, нена, карго...);
  * орфография: грузинский 'ქ' внутри слова -> мегрельское 'კ';
  * префикс отрицания: грузинский 'არ-' -> мегрельский 'ნა-';
  * местоимение 'ჩვენ' -> 'მე და შენ'.

Правила:
  * Не трогать имена, числа, ники и термины.
  * Сохранять падежные окончания (окончание переносится на новое слово).
  * Идемпотентность: повторный вызов ничего не портит.
"""

from __future__ import annotations

import re

# --------------------------------------------------------------------------
# Лексика: грузинский -> мегрельский
# --------------------------------------------------------------------------

_WORDS: dict[str, str] = {
    # Семья
    "მამა": "ბაბა",          # отец -> баба
    "ძმა": "ჯა",             # брат -> джа
    "დედა": "ნენა",          # мать -> нена
    "სიდე": "და",            # сестра -> да
    "სახლი": "ბარი",          # дом -> бари
    "სახლ": "ბარ",            # основа: სახლში -> ბარში
    "ოჯახი": "ბარი",
    # Люди и отношения
    "მეგრე": "კარგო",         # друг -> карго
    "კარგო": "კარგო",
    "ადამიანი": "კაცი",
    # Еда и напитки
    "ხალი": "პური",           # хлеб -> пури
    "ღირცი": "ფული",          # деньги -> фули
    # Время
    "ახლა": "ბრძან",          # сейчас -> брдзан
    "ახლო": "ბრძან",
    # Качество
    "კარგი": "ღია",           # хорошо -> гиа
    "ცუდი": "მარტია",         # плохо -> мартиа
    # Ключевые глаголы
    "მინდა": "მონდაო",
    "უნდა": "სჭირდება",
    "გამარჯონ": "დიდი ღვთისი",
    # Утверждение/отрицание
    "კი": "ჰა",               # да -> ха
    "არა": "ვარა",             # нет -> вара
    "არც": "ნაც",
    # Местоимения
    "ჩვენ": "მე და შენ",
    "თქვენ": "თქვენ",
    # Вопросы
    "როგორ": "მუნა",         # как -> муна
    "როდეს": "მანასობით",     # когда -> манасобит
    "რატომ": "შენდომედრო",
    # Степени
    "ძალიან": "ბარდად",        # очень -> бардад
    # Счёт
    "ყველა": "მთლაი",         # все -> мтлай
}

# --------------------------------------------------------------------------
# Орфография: грузинская -> мегрельская
# --------------------------------------------------------------------------

# 'ქ' в середине слова -> 'კ' (ქართული -> კართული)
_RE_K_INSIDE = re.compile(
    r"(?<=[აბგდევზთიკლმნოპჟრსტუფღყშჩცძწჭხჯჰ])ქ")

# Префикс отрицания: 'არ' + буква -> 'ნა' + буква
_RE_NEG_PREFIX = re.compile(
    r"^არ(?=[აბგდევზთიკლმნოპჟრსტუფღყშჩცძწჭხჯჰ])")

# Граница слова: не буква и не грузинская буква
_WORD_CHAR = r"[^\W\d_]|[\u10a0-\u10ff]"


def _orthography(text: str) -> str:
    """Грузинская орфография -> мегрельская."""
    # არ- -> ნა-   (არმართავ -> ნარმართავ)
    text = _RE_NEG_PREFIX.sub("ნა", text)
    # ქ внутри слова -> კ
    text = _RE_K_INSIDE.sub("კ", text)
    return text


def _replace_words(text: str) -> str:
    """Замена слов по словарю с сохранением падежных окончаний."""
    if not text:
        return text
    # Длинные ключи первыми — чтобы «სახლ» не перебил «სახლი»
    for key in sorted(_WORDS.keys(), key=len, reverse=True):
        if key not in text:
            continue
        repl = _WORDS[key]
        # Окончание после слова переносим на замену
        pat = re.compile(
            r"(?<!" + _WORD_CHAR + r")" + re.escape(key) + r"(" + _WORD_CHAR + r"*)")
        text = pat.sub(lambda m: repl + m.group(1), text)
    return text


def style_text(text: str) -> str:
    """Перевести грузинский текст в мегрельский."""
    if not text:
        return text
    original = text
    # 1) лексика (в т.ч. «არა» -> «ვარა»)
    text = _replace_words(text)
    # 2) отрицание и орфография
    text = _orthography(text)
    # 3) убрать двойные пробелы
    text = re.sub(r"\s{2,}", " ", text)
    return text if text.strip() else original


def to_megrel(text: str) -> str:
    """Перевести грузинский текст в мегрельский (совместимо с voice_lang)."""
    try:
        return style_text(text or "")
    except Exception:
        return text


if __name__ == "__main__":
    import sys
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    samples = [
        "გამარჯონ, მე ვარ ბაბა და ეს ჩემი ხალია.",
        "მე ვცხოვრობ სახლში და ვუყრამ ჩემ მეგრეებს.",
        "არა, ეს არ არის კარგი, მაგრამ მაინც ძალიან ბარდადაა.",
        "როდეს მოდივ? ხვალ მოვალ.",
        "ქალაქი ძალიან კარგია.",
    ]
    for s in samples:
        print(f"  {s}")
        print(f"    -> {to_megrel(s)}")
